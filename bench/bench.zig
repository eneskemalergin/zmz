//! A small benchmark that needs no external data. It writes mzML of five fixed shapes at two
//! sizes through the library itself, then times reading, decoding, indexed lookup, copying, and
//! writing, each case in its own process so peak memory is per case.
//!
//! `zmz-bench DIR` generates the inputs into DIR (kept and reused while their generator version is
//! unchanged, so runs on different commits read the same bytes), runs every case once to print its
//! checksum, then measures. With `zebrac` on the PATH it measures through zebrac (wall time, peak
//! RSS, and instructions); otherwise it times each case with the monotonic clock and reads the
//! child's peak RSS. `zmz-bench run CASE FILE` runs one case and prints its checksum.

const std = @import("std");
const builtin = @import("builtin");
const mzml = @import("zmz").mzml;

pub fn main(init: std.process.Init) !void {
    const args = try init.minimal.args.toSlice(init.arena.allocator());
    if (args.len == 4 and std.mem.eql(u8, args[1], "run")) {
        const case = std.meta.stringToEnum(Operation, args[2]) orelse return usage(init.io);
        var buffer: [256]u8 = undefined;
        var output = std.Io.File.stdout().writerStreaming(init.io, &buffer);
        try output.interface.print("{x:0>16}\n", .{try runCase(init.gpa, init.io, case, args[3])});
        try output.interface.flush();
        return;
    }
    if (args.len != 2) return usage(init.io);
    try drive(init, args[1]);
}

fn usage(io: std.Io) error{InvalidArguments}!void {
    std.Io.File.stderr().writeStreamingAll(io, "usage: zmz-bench DIR\n       zmz-bench run CASE FILE.mzML\n") catch {};
    return error.InvalidArguments;
}

// --- Inputs ---

// Bump when generated bytes change, so inputs from an older generator are not reused.
const GENERATOR_VERSION = 1;

const Shape = enum { metadata, centroid, profile, zlib, numpress };
const Size = enum { small, large };

const Plan = struct {
    spectra: usize,
    points: usize,
    /// Scans with windows, precursors with isolation windows, selected ions, and activation.
    rich: bool,
    profile: bool,
    mz: mzml.arrays.Pipeline,
    intensity: mzml.arrays.Pipeline,
};

fn planOf(shape: Shape, size: Size) Plan {
    const base: Plan = switch (shape) {
        .metadata => .{ .spectra = 4_000, .points = 16, .rich = true, .profile = false, .mz = .none, .intensity = .none },
        .centroid => .{ .spectra = 1_200, .points = 300, .rich = true, .profile = false, .mz = .none, .intensity = .none },
        .profile => .{ .spectra = 24, .points = 20_000, .rich = false, .profile = true, .mz = .none, .intensity = .none },
        .zlib => .{ .spectra = 40, .points = 20_000, .rich = false, .profile = true, .mz = .zlib, .intensity = .zlib },
        .numpress => .{ .spectra = 80, .points = 20_000, .rich = false, .profile = true, .mz = .linear, .intensity = .slof },
    };
    var plan = base;
    if (size == .large) plan.spectra *= 4;
    return plan;
}

fn inputPath(buffer: []u8, dir: []const u8, shape: Shape, size: Size) ![]const u8 {
    return std.fmt.bufPrint(buffer, "{s}/v{d}-{s}-{s}.mzML", .{ dir, GENERATOR_VERSION, @tagName(shape), @tagName(size) });
}

// Writes one input; the same plan and seed always give the same records.
fn generate(allocator: std.mem.Allocator, writer: *mzml.Writer, plan: Plan, seed: u64) !void {
    var prng = std.Random.DefaultPrng.init(seed);
    const random = prng.random();
    var builder = mzml.Builder.init(allocator, .{});
    defer builder.deinit();
    try writer.writeHeader(try header(&builder));
    builder.reset();
    var encoder = mzml.arrays.Encoder.init(allocator, .fast);
    defer encoder.deinit();
    const mz = try allocator.alloc(f64, plan.points);
    defer allocator.free(mz);
    const intensity = try allocator.alloc(f32, plan.points);
    defer allocator.free(intensity);
    try writer.beginList(.spectrum_list, plan.spectra, "processing");
    var last_survey: usize = 0;
    for (0..plan.spectra) |index| {
        builder.reset();
        encoder.reset();
        const survey = plan.profile or index % 5 == 0;
        if (survey) last_survey = index;
        fillValues(random, plan, mz, intensity);
        var id_text: [32]u8 = undefined;
        const id = try std.fmt.bufPrint(&id_text, "scan={d}", .{index + 1});
        var text: Text = .{};
        var nodes: [2]mzml.model.Node = undefined;
        const children = if (plan.rich) try richChildren(&builder, random, &text, index, last_survey, survey, mz, &nodes) else &.{};
        const mz_array = try builder.prepareArray(f64, mz, .{
            .cv_ref = "MS",
            .role = .{ .cv_ref = "MS", .accession = mzml.model.Terms.MZ_ARRAY, .name = "m/z array" },
            .encoding = try encodeOptions(plan.mz, f64, mz),
        }, &encoder);
        const intensity_array = try builder.prepareArray(f32, intensity, .{
            .cv_ref = "MS",
            .role = .{ .cv_ref = "MS", .accession = mzml.model.Terms.INTENSITY_ARRAY, .name = "intensity array" },
            .encoding = try encodeOptions(plan.intensity, f32, intensity),
        }, &encoder);
        const record = try builder.record(.spectrum, id, index, plan.points, &.{
            cvParam("MS:1000511", "ms level", if (survey) "1" else "2", null),
            cvParam(if (plan.profile) "MS:1000128" else "MS:1000127", if (plan.profile) "profile spectrum" else "centroid spectrum", "", null),
            cvParam("MS:1000130", "positive scan", "", null),
        }, children, &.{ mz_array.array, intensity_array.array });
        try writer.writeRecordWithArrays(record.node, &.{ mz_array.payload, intensity_array.payload });
    }
    try writer.endList();
    try writer.finish();
}

fn encodeOptions(pipeline: mzml.arrays.Pipeline, comptime T: type, values: []const T) !mzml.arrays.EncodeOptions {
    return switch (pipeline) {
        .linear => .{ .pipeline = .linear, .fixed_point = try mzml.numpress.optimalLinearFixedPoint(values) },
        .slof => .{ .pipeline = .slof, .fixed_point = try mzml.numpress.optimalSlofFixedPoint(values) },
        else => .{ .pipeline = pipeline },
    };
}

// Centroid m/z values rise in random steps; profile m/z values rise evenly, with peaks of a few
// samples' width over noise.
fn fillValues(random: std.Random, plan: Plan, mz: []f64, intensity: []f32) void {
    if (plan.profile) {
        for (mz, intensity, 0..) |*m, *i, j| {
            m.* = 300.0 + @as(f64, @floatFromInt(j)) * 0.05;
            i.* = random.float(f32) * 50.0;
        }
        for (0..plan.points / 200) |_| {
            const center = random.uintLessThan(usize, plan.points);
            const height = 1e4 + random.float(f32) * 1e6;
            const first = center -| 6;
            for (intensity[first..@min(center + 7, plan.points)], first..) |*i, j| {
                const distance: f32 = @floatFromInt(@as(isize, @intCast(j)) - @as(isize, @intCast(center)));
                i.* += height * @exp(-distance * distance / 4.0);
            }
        }
    } else {
        var value: f64 = 100.0 + random.float(f64) * 5.0;
        const step = 1900.0 / @as(f64, @floatFromInt(plan.points));
        for (mz, intensity) |*m, *i| {
            value += random.float(f64) * 2.0 * step;
            m.* = value;
            i.* = 1e3 + random.floatExp(f32) * 5e4;
        }
    }
}

// Formatted values for one record; the builder copies them into the record.
const Text = struct {
    buffer: [512]u8 = undefined,
    used: usize = 0,

    fn print(self: *Text, comptime format: []const u8, args: anytype) ![]const u8 {
        const written = try std.fmt.bufPrint(self.buffer[self.used..], format, args);
        self.used += written.len;
        return written;
    }
};

fn cvParam(accession: []const u8, name: []const u8, value: []const u8, unit: ?[3][]const u8) mzml.cv.Entry {
    return .{ .cv = .{
        .cv_ref = "MS",
        .accession = .{ .raw = accession },
        .name = name,
        .value = value,
        .unit = if (unit) |u| .{ .cv_ref = u[0], .accession = .{ .raw = u[1] }, .name = u[2] } else .{},
    } };
}

const MINUTE = [3][]const u8{ "UO", "UO:0000031", "minute" };
const MILLISECOND = [3][]const u8{ "UO", "UO:0000028", "millisecond" };
const MZ = [3][]const u8{ "MS", "MS:1000040", "m/z" };
const COUNTS = [3][]const u8{ "MS", "MS:1000131", "number of detector counts" };
const ELECTRONVOLT = [3][]const u8{ "UO", "UO:0000266", "electronvolt" };

// A scan with its time, filter, injection time, and window, and for MS2 a precursor with its
// isolation window, selected ion, and activation, as instruments write them.
// The nodes go in `out`; their children are copies the builder owns.
fn richChildren(
    builder: *mzml.Builder,
    random: std.Random,
    text: *Text,
    index: usize,
    survey_index: usize,
    survey: bool,
    mz: []const f64,
    out: *[2]mzml.model.Node,
) ![]const mzml.model.Node {
    const time = try text.print("{d:.4}", .{@as(f64, @floatFromInt(index)) * 0.0051});
    const target = mz[mz.len / 2] + random.float(f64);
    const scan: mzml.model.Node = .{
        .kind = .scan,
        .attributes = &.{.{ .name = "instrumentConfigurationRef", .value = "instrument" }},
        .params = &.{
            cvParam("MS:1000016", "scan start time", time, MINUTE),
            cvParam("MS:1000512", "filter string", if (survey) "FTMS + p NSI Full ms [350.0000-1800.0000]" else "ITMS + c NSI d Full ms2 cid35.00 [100.0000-2000.0000]", null),
            cvParam("MS:1000927", "ion injection time", try text.print("{d:.3}", .{random.float(f64) * 50.0}), MILLISECOND),
        },
        .children = &.{try builder.list(.scan_window_list, &.{.{ .kind = .scan_window, .params = &.{
            cvParam("MS:1000501", "scan window lower limit", "100", MZ),
            cvParam("MS:1000500", "scan window upper limit", "2000", MZ),
        } }})},
    };
    out[0] = try builder.list(.scan_list, &.{scan});
    if (survey) return out[0..1];
    const reference = try text.print("scan={d}", .{survey_index + 1});
    const precursor: mzml.model.Node = .{
        .kind = .precursor,
        .attributes = &.{.{ .name = "spectrumRef", .value = reference }},
        .children = &.{
            .{ .kind = .isolation_window, .params = &.{
                cvParam("MS:1000827", "isolation window target m/z", try text.print("{d:.5}", .{target}), MZ),
                cvParam("MS:1000828", "isolation window lower offset", "1", MZ),
                cvParam("MS:1000829", "isolation window upper offset", "1", MZ),
            } },
            try builder.list(.selected_ion_list, &.{.{ .kind = .selected_ion, .params = &.{
                cvParam("MS:1000744", "selected ion m/z", try text.print("{d:.5}", .{target}), MZ),
                cvParam("MS:1000041", "charge state", try text.print("{d}", .{2 + random.uintLessThan(u8, 3)}), null),
                cvParam("MS:1000042", "peak intensity", try text.print("{d:.1}", .{random.float(f64) * 1e7}), COUNTS),
            } }}),
            .{ .kind = .activation, .params = &.{
                cvParam("MS:1000133", "collision-induced dissociation", "", null),
                cvParam("MS:1000045", "collision energy", "35", ELECTRONVOLT),
            } },
        },
    };
    out[1] = try builder.list(.precursor_list, &.{precursor});
    return out[0..2];
}

