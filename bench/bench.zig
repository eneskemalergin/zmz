// --- Cases ---

const Operation = enum {
    /// Forward reading with payloads skipped: ID, MS level, and scan time per spectrum.
    meta,
    /// Forward reading that decodes every array and reads every value.
    full,
    /// Every XML event through the end.
    events,
    /// Opening the embedded index, then decoding every tenth spectrum by position.
    lookup,
    /// Copying every item to a discarding sink.
    copy,
    /// Generating the input again into a discarding sink: building and encoding.
    write,
};

const Case = struct { operation: Operation, shape: Shape };

const CASES = [_]Case{
    .{ .operation = .meta, .shape = .metadata },
    .{ .operation = .events, .shape = .metadata },
    .{ .operation = .copy, .shape = .metadata },
    .{ .operation = .full, .shape = .centroid },
    .{ .operation = .full, .shape = .profile },
    .{ .operation = .full, .shape = .zlib },
    .{ .operation = .full, .shape = .numpress },
    .{ .operation = .lookup, .shape = .zlib },
    .{ .operation = .write, .shape = .centroid },
    .{ .operation = .write, .shape = .zlib },
    .{ .operation = .write, .shape = .numpress },
};

// A checksum over what the case read, so every run can be compared and no work is skipped.
const Checksum = struct {
    hash: std.hash.Wyhash = .init(0),

    fn bytes(self: *Checksum, value: []const u8) void {
        self.hash.update(value);
    }

    fn number(self: *Checksum, value: anytype) void {
        self.hash.update(std.mem.asBytes(&value));
    }

    fn decoded(self: *Checksum, arrays: *const mzml.DecodedArrays) void {
        for (0..arrays.len()) |position| switch (arrays.get(position).?.values) {
            inline else => |values| self.hash.update(std.mem.sliceAsBytes(values)),
        };
    }
};

fn runCase(allocator: std.mem.Allocator, io: std.Io, operation: Operation, path: []const u8) !u64 {
    return switch (operation) {
        .meta => meta(allocator, io, path),
        .full => full(allocator, io, path),
        .events => events(allocator, io, path),
        .lookup => lookup(allocator, io, path),
        .copy => copy(allocator, io, path),
        .write => write(allocator, path),
    };
}

fn meta(allocator: std.mem.Allocator, io: std.Io, path: []const u8) !u64 {
    const file = try std.Io.Dir.cwd().openFile(io, path, .{});
    defer file.close(io);
    var buffer: [64 * 1024]u8 = undefined;
    var input = file.reader(io, &buffer);
    var reader = try mzml.StreamReader.init(allocator, &input.interface, .{ .payload = .skip });
    defer reader.deinit();
    const groups = (try reader.readHeader()).groups;
    var checksum: Checksum = .{};
    while (try reader.nextRecord()) |record| {
        checksum.bytes(record.id);
        checksum.number(try record.msLevel(groups));
        for (record.scans()) |scan| if (try scan.scanStartTime(groups)) |time| checksum.number(time.value);
    }
    return checksum.hash.final();
}

fn full(allocator: std.mem.Allocator, io: std.Io, path: []const u8) !u64 {
    const file = try std.Io.Dir.cwd().openFile(io, path, .{});
    defer file.close(io);
    var buffer: [64 * 1024]u8 = undefined;
    var input = file.reader(io, &buffer);
    var reader = try mzml.StreamReader.init(allocator, &input.interface, .{ .payload = .skip });
    defer reader.deinit();
    _ = try reader.readHeader();
    var decoded = mzml.DecodedArrays.init(allocator, .{});
    defer decoded.deinit();
    var checksum: Checksum = .{};
    while (try reader.nextDecodedRecord(&decoded)) |record| {
        checksum.bytes(record.id);
        checksum.decoded(&decoded);
    }
    return checksum.hash.final();
}

fn events(allocator: std.mem.Allocator, io: std.Io, path: []const u8) !u64 {
    const file = try std.Io.Dir.cwd().openFile(io, path, .{});
    defer file.close(io);
    var buffer: [64 * 1024]u8 = undefined;
    var input = file.reader(io, &buffer);
    var stream = try mzml.Events.init(allocator, &input.interface, .{});
    defer stream.deinit();
    var checksum: Checksum = .{};
    while (try stream.next()) |event| checksum.number(event.span.start);
    return checksum.hash.final();
}

// Writing needs every record's Base64 text, so payloads are retained.
fn copy(allocator: std.mem.Allocator, io: std.Io, path: []const u8) !u64 {
    const file = try std.Io.Dir.cwd().openFile(io, path, .{});
    defer file.close(io);
    var buffer: [64 * 1024]u8 = undefined;
    var input = file.reader(io, &buffer);
    var reader = try mzml.StreamReader.init(allocator, &input.interface, .{ .payload = .retain });
    defer reader.deinit();
    var output_buffer: [64 * 1024]u8 = undefined;
    var sink: std.Io.Writer.Hashing(std.hash.Wyhash) = .initHasher(.init(0), &output_buffer);
    var writer = try mzml.Writer.init(allocator, &sink.writer, .{});
    defer writer.deinit();
    try writer.writeHeader((try reader.readHeader()).*);
    while (try reader.nextItem()) |item| try writer.writeItem(item);
    try writer.finish();
    try sink.writer.flush();
    return sink.hasher.final();
}

fn lookup(allocator: std.mem.Allocator, io: std.Io, path: []const u8) !u64 {
    const file = try std.Io.Dir.cwd().openFile(io, path, .{});
    defer file.close(io);
    var index = try mzml.IndexedReader.build(allocator, .{ .file = .{ .handle = file, .io = io } }, .{});
    defer index.deinit();
    var decoded = mzml.DecodedArrays.init(allocator, .{});
    defer decoded.deinit();
    var checksum: Checksum = .{};
    var ordinal: usize = 0;
    while (try index.atDecoded(allocator, .spectrum, ordinal, &decoded)) |found| : (ordinal += 10) {
        var record = found;
        defer record.deinit();
        checksum.bytes(record.value.id);
        checksum.decoded(&decoded);
    }
    return checksum.hash.final();
}

// Generates the input that `path` names again, into a hashing sink instead of a file.
fn write(allocator: std.mem.Allocator, path: []const u8) !u64 {
    const input = try inputOf(path);
    var buffer: [64 * 1024]u8 = undefined;
    var sink: std.Io.Writer.Hashing(std.hash.Wyhash) = .initHasher(.init(0), &buffer);
    var writer = try mzml.Writer.initIndexed(allocator, &sink.writer, .{}, .{});
    defer writer.deinit();
    try generate(allocator, &writer, planOf(input.shape, input.size), @intFromEnum(input.shape));
    try sink.writer.flush();
    return sink.hasher.final();
}

// The shape and size of an input path that `inputPath` made: `vVERSION-SHAPE-SIZE.mzML`.
fn inputOf(path: []const u8) error{InvalidArguments}!struct { shape: Shape, size: Size } {
    var parts = std.mem.splitScalar(u8, std.fs.path.stem(path), '-');
    _ = parts.next();
    const shape = std.meta.stringToEnum(Shape, parts.next() orelse "") orelse return error.InvalidArguments;
    const size = std.meta.stringToEnum(Size, parts.next() orelse "") orelse return error.InvalidArguments;
    if (parts.next() != null) return error.InvalidArguments;
    return .{ .shape = shape, .size = size };
}

// --- Driver ---

const Measurement = struct { wall_ns: f64, peak_rss: f64, instructions: ?f64 };

fn drive(init: std.process.Init, dir_path: []const u8) !void {
    const allocator = init.arena.allocator();
    const io = init.io;
    var output_buffer: [4096]u8 = undefined;
    var stdout = std.Io.File.stdout().writerStreaming(io, &output_buffer);
    const out = &stdout.interface;
    try std.Io.Dir.cwd().createDirPath(io, dir_path);
    const self_path = try std.process.executablePathAlloc(io, allocator);

    // Inputs, generated once per generator version.
    var sizes: [@typeInfo(Shape).@"enum".fields.len][2]u64 = undefined;
    for (std.enums.values(Shape)) |shape| for (std.enums.values(Size)) |size| {
        var path_buffer: [std.fs.max_path_bytes]u8 = undefined;
        const path = try inputPath(&path_buffer, dir_path, shape, size);
        const existing = std.Io.Dir.cwd().statFile(io, path, .{}) catch null;
        if (existing == null) {
            try out.print("generating {s}\n", .{path});
            try out.flush();
            try writeInput(init.gpa, io, path, shape, size);
        }
        sizes[@intFromEnum(shape)][@intFromEnum(size)] = (try std.Io.Dir.cwd().statFile(io, path, .{})).size;
    };

    // Commands, in case order, small then large.
    var commands: std.ArrayList([]const []const u8) = .empty;
    var labels: std.ArrayList([]const u8) = .empty;
    var bytes: std.ArrayList(u64) = .empty;
    for (std.enums.values(Size)) |size| for (CASES) |case| {
        var path_buffer: [std.fs.max_path_bytes]u8 = undefined;
        const path = try allocator.dupe(u8, try inputPath(&path_buffer, dir_path, case.shape, size));
        try commands.append(allocator, try allocator.dupe([]const u8, &.{ self_path, "run", @tagName(case.operation), path }));
        try labels.append(allocator, try std.fmt.allocPrint(allocator, "{s} {s} {s}", .{ @tagName(case.operation), @tagName(case.shape), @tagName(size) }));
        try bytes.append(allocator, sizes[@intFromEnum(case.shape)][@intFromEnum(size)]);
    };

    // One run each: the checksums, which must not change unless the inputs or results do.
    const checksums = try allocator.alloc([]const u8, commands.items.len);
    for (commands.items, checksums) |argv, *checksum| {
        const result = try std.process.run(allocator, io, .{ .argv = argv });
        if (result.term != .exited or result.term.exited != 0) {
            std.debug.print("{s}: {s}", .{ argv[2], result.stderr });
            return error.CaseFailed;
        }
        checksum.* = std.mem.trimEnd(u8, result.stdout, "\n");
    }

    const measurements = try allocator.alloc(Measurement, commands.items.len);
    const tool = if (try zebracAvailable(allocator, io)) "zebrac" else "monotonic clock";
    try out.print("measuring {d} cases with {s}\n", .{ commands.items.len, tool });
    try out.flush();
    if (std.mem.eql(u8, tool, "zebrac"))
        try measureWithZebrac(allocator, io, dir_path, commands.items, measurements)
    else
        try measureWithClock(io, commands.items, measurements);

    try out.print("\nzmz-bench: generator v{d}, Zig {s}, {s}-{s}, ReleaseFast, {s}\n\n", .{
        GENERATOR_VERSION, builtin.zig_version_string, @tagName(builtin.cpu.arch), @tagName(builtin.os.tag), tool,
    });
    try out.print("{s:<24} {s:>8} {s:>10} {s:>9} {s:>9} {s:>13}  {s}\n", .{ "case", "MiB", "wall ms", "MiB/s", "RSS MiB", "instructions", "checksum" });
    for (labels.items, bytes.items, measurements, checksums, 0..) |label, size, measurement, checksum, i| {
        const mib = @as(f64, @floatFromInt(size)) / (1024.0 * 1024.0);
        const ms = measurement.wall_ns / 1e6;
        try out.print("{s:<24} {d:>8.1} {d:>10.1} ", .{ label, mib, ms });
        // A lookup reads a tenth of the records, so file size over time is not its throughput.
        if (CASES[i % CASES.len].operation == .lookup) try out.print("{s:>9} ", .{"-"}) else try out.print("{d:>9.1} ", .{mib / (ms / 1e3)});
        try out.print("{d:>9.1} ", .{measurement.peak_rss / (1024.0 * 1024.0)});
        if (measurement.instructions) |count| try out.print("{d:>12.1}M", .{count / 1e6}) else try out.print("{s:>13}", .{"-"});
        try out.print("  {s}\n", .{checksum});
    }
    try out.flush();
}

// Written under a temporary name and renamed when complete, so an interrupted run leaves no input
// that looks finished. Indexed file output reads the file back for its checksum.
fn writeInput(allocator: std.mem.Allocator, io: std.Io, path: []const u8, shape: Shape, size: Size) !void {
    const dir = std.Io.Dir.cwd();
    var partial_buffer: [std.fs.max_path_bytes]u8 = undefined;
    const partial = try std.fmt.bufPrint(&partial_buffer, "{s}.partial", .{path});
    const file = try dir.createFile(io, partial, .{ .read = true });
    errdefer dir.deleteFile(io, partial) catch {};
    {
        defer file.close(io);
        var buffer: [64 * 1024]u8 = undefined;
        var output = file.writer(io, &buffer);
        var writer = try mzml.Writer.initFile(allocator, &output, .{}, .{});
        defer writer.deinit();
        try generate(allocator, &writer, planOf(shape, size), @intFromEnum(shape));
        try output.interface.flush();
    }
    try dir.rename(partial, dir, path, io);
}

fn zebracAvailable(allocator: std.mem.Allocator, io: std.Io) !bool {
    const result = std.process.run(allocator, io, .{ .argv = &.{ "zebrac", "--version" } }) catch return false;
    return result.term == .exited and result.term.exited == 0;
}

// Medians of every case, sampled in interleaved rounds.
fn measureWithZebrac(allocator: std.mem.Allocator, io: std.Io, dir_path: []const u8, commands: []const []const []const u8, measurements: []Measurement) !void {
    const json_path = try std.fmt.allocPrint(allocator, "{s}/zebrac.json", .{dir_path});
    var argv: std.ArrayList([]const u8) = .empty;
    try argv.appendSlice(allocator, &.{ "zebrac", "-q", "--duration", "1000", "--min-samples", "5", "--warmup", "1", try std.fmt.allocPrint(allocator, "--json={s}", .{json_path}), "--" });
    for (commands) |command| {
        var line: std.Io.Writer.Allocating = .init(allocator);
        for (command, 0..) |word, i| try line.writer.print("{s}'{s}'", .{ if (i == 0) "" else " ", word });
        try argv.append(allocator, line.written());
    }
    const result = try std.process.run(allocator, io, .{ .argv = argv.items });
    if (result.term != .exited or result.term.exited != 0) {
        std.debug.print("{s}", .{result.stderr});
        return error.ZebracFailed;
    }
    const Stat = struct { median: f64 };
    const Report = struct { results: []const struct { wall_time: Stat, peak_rss: Stat, instructions: Stat } };
    const json = try std.Io.Dir.cwd().readFileAlloc(io, json_path, allocator, .limited(16 << 20));
    const report = try std.json.parseFromSliceLeaky(Report, allocator, json, .{ .ignore_unknown_fields = true });
    if (report.results.len != commands.len) return error.ZebracFailed;
    for (report.results, measurements) |entry, *measurement| measurement.* = .{
        .wall_ns = entry.wall_time.median,
        .peak_rss = entry.peak_rss.median,
        .instructions = entry.instructions.median,
    };
}

// Medians of five runs per case after one unmeasured run.
fn measureWithClock(io: std.Io, commands: []const []const []const u8, measurements: []Measurement) !void {
    const runs = 5;
    for (commands, measurements) |argv, *measurement| {
        var walls: [runs]f64 = undefined;
        var peaks: [runs]f64 = undefined;
        for (0..runs + 1) |run| {
            const start = std.Io.Timestamp.now(io, .awake);
            var child = try std.process.spawn(io, .{
                .argv = argv,
                .stdout = .ignore,
                .request_resource_usage_statistics = true,
            });
            const term = try child.wait(io);
            const elapsed = start.untilNow(io, .awake);
            if (term != .exited or term.exited != 0) return error.CaseFailed;
            if (run == 0) continue;
            walls[run - 1] = @floatFromInt(elapsed.toNanoseconds());
            peaks[run - 1] = @floatFromInt(child.resource_usage_statistics.getMaxRss() orelse 0);
        }
        std.mem.sort(f64, &walls, {}, std.sort.asc(f64));
        std.mem.sort(f64, &peaks, {}, std.sort.asc(f64));
        measurement.* = .{ .wall_ns = walls[runs / 2], .peak_rss = peaks[runs / 2], .instructions = null };
    }
}

test "[unit] - [zmz-bench]: generated inputs repeat, read back exactly, and open through their index" {
    const allocator = std.testing.allocator;
    for (std.enums.values(Shape)) |shape| {
        var plan = planOf(shape, .small);
        plan.spectra = 6;
        plan.points = 400;
        var first: std.Io.Writer.Allocating = .init(allocator);
        defer first.deinit();
        var second: std.Io.Writer.Allocating = .init(allocator);
        defer second.deinit();
        for ([_]*std.Io.Writer.Allocating{ &first, &second }) |sink| {
            var writer = try mzml.Writer.initIndexed(allocator, &sink.writer, .{}, .{});
            defer writer.deinit();
            try generate(allocator, &writer, plan, @intFromEnum(shape));
        }
        try std.testing.expectEqualStrings(first.written(), second.written());

        var prng = std.Random.DefaultPrng.init(@intFromEnum(shape));
        const mz = try allocator.alloc(f64, plan.points);
        defer allocator.free(mz);
        const intensity = try allocator.alloc(f32, plan.points);
        defer allocator.free(intensity);
        var input = std.Io.Reader.fixed(first.written());
        var reader = try mzml.StreamReader.init(allocator, &input, .{});
        defer reader.deinit();
        const groups = (try reader.readHeader()).groups;
        var decoded = mzml.DecodedArrays.init(allocator, .{});
        defer decoded.deinit();
        var records: usize = 0;
        while (try reader.nextDecodedRecord(&decoded)) |record| : (records += 1) {
            // The generator draws each record's values before its metadata; repeat the draws.
            fillValues(prng.random(), plan, mz, intensity);
            if (plan.rich) {
                var text: Text = .{};
                var builder = mzml.Builder.init(allocator, .{});
                defer builder.deinit();
                var nodes: [2]mzml.model.Node = undefined;
                const survey = records % 5 == 0;
                _ = try richChildren(&builder, prng.random(), &text, records, 0, survey, mz, &nodes);
                try std.testing.expectEqual(@as(?i32, if (survey) 1 else 2), try record.msLevel(groups));
            }
            try std.testing.expectEqual(@as(usize, 2), decoded.len());
            const decoded_mz = decoded.get(0).?.values.float64;
            if (plan.mz == .linear) {
                for (mz, decoded_mz) |expected, actual| try std.testing.expectApproxEqAbs(expected, actual, 1e-6);
            } else {
                try std.testing.expectEqualSlices(f64, mz, decoded_mz);
                try std.testing.expectEqualSlices(f32, intensity, decoded.get(1).?.values.float32);
            }
        }
        try std.testing.expectEqual(plan.spectra, records);
        var index = try mzml.IndexedReader.build(allocator, .{ .bytes = first.written() }, .{});
        defer index.deinit();
        try std.testing.expectEqual(plan.spectra, index.entryCount());
    }
}
