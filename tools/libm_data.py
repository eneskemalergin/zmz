"""Generates src/binary/libm_data.zig from musl's copies of ARM optimized-routines exp_data.c and
log_data.c (MIT, Copyright (c) 2018 Arm Limited), the algorithm glibc's exp and log use.
Usage: tools/libm_data.py MUSL_MATH_DIR (src/math of a musl source tree; Zig 0.15 ships one
under lib/libc/musl)"""
import re, sys

src = sys.argv[1]
NUM = r"-?0x[0-9a-fA-F.]+(?:p[-+]?\d+)?"


def block(text, name):
    start = text.index(f".{name} = {{")
    depth, i = 0, text.index("{", start)
    for j in range(i, len(text)):
        depth += text[j] == "{"
        depth -= text[j] == "}"
        if depth == 0:
            body = text[i + 1:j]
            break
    body = re.sub(r"//.*", "", body)
    return re.findall(NUM, body)


def scalar(text, name):
    return re.search(rf"\.{name} = ({NUM})", text).group(1)


exp = open(f"{src}/exp_data.c").read()
log = open(f"{src}/log_data.c").read()
exp_tab = block(exp, "tab")
log_tab = block(log, "tab")
log_tab2 = block(log, "tab2")
assert len(exp_tab) == 256 and len(log_tab) == 256 and len(log_tab2) == 256
poly = block(exp, "poly")
assert len(poly) == 4
lpoly, lpoly1 = block(log, "poly"), block(log, "poly1")
assert len(lpoly) == 5 and len(lpoly1) == 11


def zf(x):
    # C hex floats such as 0x1p-1 or 0x1.8p52 are valid Zig float literals; 0x0 needs a point.
    return x if "." in x or "p" in x else x + ".0"


