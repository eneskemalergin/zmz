out = ["//! Generated by tools/libm_data.py from musl's ARM optimized-routines exp_data.c and",
       "//! log_data.c: the tables glibc's exp and log use.",
       "//!"] + [("//! " + line).rstrip() for line in NOTICE.splitlines()] + [
       "", "pub const exp_invln2n: f64 = 0x1.71547652b82fep0 * 128.0;",
       "pub const exp_shift: f64 = 0x1.8p52;",
       f"pub const exp_negln2hin: f64 = {scalar(exp, 'negln2hiN')};",
       f"pub const exp_negln2lon: f64 = {scalar(exp, 'negln2loN')};",
       "/// C2 to C5.",
       "pub const exp_poly = [4]f64{ " + ", ".join(poly) + " };",
       "/// Pairs of (tail bits, scale bits) for 2^(i/128).",
       "pub const exp_tab = [256]u64{"] + [f"    {x}," for x in exp_tab] + ["};", "",
       f"pub const log_ln2hi: f64 = {scalar(log, 'ln2hi')};",
       f"pub const log_ln2lo: f64 = {scalar(log, 'ln2lo')};",
       "/// A[0] to A[4]; the first coefficient, 1, is implicit.",
       "pub const log_poly = [5]f64{ " + ", ".join(map(zf, lpoly)) + " };",
       "/// B[0] to B[10] for inputs near 1.",
       "pub const log_poly1 = [11]f64{ " + ", ".join(map(zf, lpoly1)) + " };",
       "pub const LogEntry = struct { a: f64, b: f64 };",
       "/// (invc, logc) per subinterval.",
       "pub const log_tab = [128]LogEntry{"] + [f"    .{{ .a = {zf(log_tab[2*i])}, .b = {zf(log_tab[2*i+1])} }}," for i in range(128)] + ["};",
       "/// (chi, clo) per subinterval, for the build without FMA.",
       "pub const log_tab2 = [128]LogEntry{"] + [f"    .{{ .a = {zf(log_tab2[2*i])}, .b = {zf(log_tab2[2*i+1])} }}," for i in range(128)] + ["};", ""]
open("src/binary/libm_data.zig", "w").write("\n".join(out))
print("wrote src/binary/libm_data.zig")
