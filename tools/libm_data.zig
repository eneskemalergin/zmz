fn render(allocator: std.mem.Allocator, w: *std.Io.Writer, exp: []const u8, log: []const u8) !void {
    const exp_tab = try block(allocator, exp, "tab", 256);
    const exp_poly = try block(allocator, exp, "poly", 4);
    const log_tab = try block(allocator, log, "tab", 256);
    const log_tab2 = try block(allocator, log, "tab2", 256);
    const log_poly = try block(allocator, log, "poly", 5);
    const log_poly1 = try block(allocator, log, "poly1", 11);

    try w.writeAll("//! Generated by tools/libm_data.zig from musl's ARM optimized-routines exp_data.c and\n" ++
        "//! log_data.c: the tables glibc's exp and log use.\n//!\n");
    var lines = std.mem.splitScalar(u8, NOTICE, '\n');
    while (lines.next()) |line| try w.print("{s}\n", .{std.mem.trimEnd(u8, try std.fmt.allocPrint(allocator, "//! {s}", .{line}), " ")});
    try w.writeAll("\npub const exp_invln2n: f64 = 0x1.71547652b82fep0 * 128.0;\npub const exp_shift: f64 = 0x1.8p52;\n");
    try w.print("pub const exp_negln2hin: f64 = {s};\n", .{try scalar(exp, "negln2hiN")});
    try w.print("pub const exp_negln2lon: f64 = {s};\n", .{try scalar(exp, "negln2loN")});
    try w.writeAll("/// C2 to C5.\npub const exp_poly = [4]f64{ ");
    try list(w, exp_poly);
    try w.writeAll(" };\n/// Pairs of (tail bits, scale bits) for 2^(i/128).\npub const exp_tab = [256]u64{\n");
    for (exp_tab) |value| try w.print("    {s},\n", .{value});
    try w.writeAll("};\n\n");
    try w.print("pub const log_ln2hi: f64 = {s};\n", .{try scalar(log, "ln2hi")});
    try w.print("pub const log_ln2lo: f64 = {s};\n", .{try scalar(log, "ln2lo")});
    try w.writeAll("/// A[0] to A[4]; the first coefficient, 1, is implicit.\npub const log_poly = [5]f64{ ");
    try list(w, log_poly);
    try w.writeAll(" };\n/// B[0] to B[10] for inputs near 1.\npub const log_poly1 = [11]f64{ ");
    try list(w, log_poly1);
    try w.writeAll(" };\npub const LogEntry = struct { a: f64, b: f64 };\n/// (invc, logc) per subinterval.\npub const log_tab = [128]LogEntry{\n");
    try entries(w, log_tab);
    try w.writeAll("};\n/// (chi, clo) per subinterval, for the build without FMA.\npub const log_tab2 = [128]LogEntry{\n");
    try entries(w, log_tab2);
    try w.writeAll("};\n");
}

fn list(w: *std.Io.Writer, values: []const []const u8) !void {
    for (values, 0..) |value, i| try w.print("{s}{f}", .{ if (i == 0) "" else ", ", float(value) });
}

fn entries(w: *std.Io.Writer, values: []const []const u8) !void {
    for (0..values.len / 2) |i| try w.print("    .{{ .a = {f}, .b = {f} }},\n", .{ float(values[2 * i]), float(values[2 * i + 1]) });
}

// A C hex float as a Zig float literal: 0x1p-1 and 0x1.8p52 already are; 0x0 needs a point.
const Float = struct {
    text: []const u8,

    pub fn format(self: Float, w: *std.Io.Writer) std.Io.Writer.Error!void {
        try w.writeAll(self.text);
        if (std.mem.indexOfAny(u8, self.text, ".p") == null) try w.writeAll(".0");
    }
};

fn float(text: []const u8) Float {
    return .{ .text = text };
}

// The number after `.NAME = ` in a C designated initializer.
fn scalar(text: []const u8, name: []const u8) ![]const u8 {
    var key: [64]u8 = undefined;
    const start = (std.mem.indexOf(u8, text, try std.fmt.bufPrint(&key, ".{s} = ", .{name})) orelse return error.MissingTable) + name.len + 4;
    return number(text, start) orelse error.MissingTable;
}

// The numbers inside `.NAME = { ... }`, comments removed; exactly `expected` of them.
fn block(allocator: std.mem.Allocator, text: []const u8, name: []const u8, expected: usize) ![]const []const u8 {
    var key: [64]u8 = undefined;
    const open = (std.mem.indexOf(u8, text, try std.fmt.bufPrint(&key, ".{s} = {{", .{name})) orelse return error.MissingTable) + name.len + 4;
    var depth: usize = 0;
    const close = for (text[open..], open..) |byte, i| {
        if (byte == '{') depth += 1;
        if (byte == '}') {
            depth -= 1;
            if (depth == 0) break i;
        }
    } else return error.MissingTable;
    var values: std.ArrayList([]const u8) = .empty;
    var lines = std.mem.splitScalar(u8, text[open + 1 .. close], '\n');
    while (lines.next()) |full_line| {
        const line = if (std.mem.indexOf(u8, full_line, "//")) |comment| full_line[0..comment] else full_line;
        var i: usize = 0;
        while (i < line.len) {
            if (number(line, i)) |found| {
                try values.append(allocator, found);
                i += found.len;
            } else i += 1;
        }
    }
    if (values.items.len != expected) return error.UnexpectedTableSize;
    return values.items;
}

// A hex number at `start`: an optional minus, 0x, hex digits and points, and an optional binary
// exponent.
fn number(text: []const u8, start: usize) ?[]const u8 {
    var i = start;
    if (i < text.len and text[i] == '-') i += 1;
    if (!std.mem.startsWith(u8, text[i..], "0x")) return null;
    i += 2;
    const digits = i;
    while (i < text.len and (std.ascii.isHex(text[i]) or text[i] == '.')) i += 1;
    if (i == digits) return null;
    if (i < text.len and text[i] == 'p') {
        var j = i + 1;
        if (j < text.len and (text[j] == '-' or text[j] == '+')) j += 1;
        const exponent = j;
        while (j < text.len and std.ascii.isDigit(text[j])) j += 1;
        if (j > exponent) i = j;
    }
    return text[start..i];
}

test "[unit] - [libm-data]: reads C hex numbers, table bodies, and writes Zig float literals" {
    try std.testing.expectEqualStrings("-0x1.62e42fefa0000p-8", number("-0x1.62e42fefa0000p-8,", 0).?);
    try std.testing.expectEqualStrings("0x3ff0000000000000", number("0x3ff0000000000000, ", 0).?);
    try std.testing.expectEqualStrings("0x1p-1", number("0x1p-1}", 0).?);
    // A `p` without digits is not an exponent.
    try std.testing.expectEqualStrings("0x1.8", number("0x1.8p,", 0).?);
    try std.testing.expectEqual(null, number("x0x1", 0));
    try std.testing.expectEqual(null, number("0x,", 0));

    const source =
        \\.scale = 0x1p-1,
        \\.poly = {
        \\// 0x9 in a comment is not a value
        \\0x1.5p-2, -0x0, { 0x3 }, // trailing 0x7
        \\},
        \\.poly1 = { 0x4 },
    ;
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const values = try block(arena.allocator(), source, "poly", 3);
    try std.testing.expectEqualStrings("0x1.5p-2", values[0]);
    try std.testing.expectEqualStrings("-0x0", values[1]);
    try std.testing.expectEqualStrings("0x3", values[2]);
    try std.testing.expectEqualStrings("0x4", (try block(arena.allocator(), source, "poly1", 1))[0]);
    try std.testing.expectError(error.UnexpectedTableSize, block(arena.allocator(), source, "poly", 4));
    try std.testing.expectError(error.MissingTable, block(arena.allocator(), source, "tab", 1));
    try std.testing.expectEqualStrings("0x1p-1", try scalar(source, "scale"));

    var buffer: [64]u8 = undefined;
    var writer = std.Io.Writer.fixed(&buffer);
    try list(&writer, &.{ "0x0", "0x1p-1", "-0x1.8p52" });
    try std.testing.expectEqualStrings("0x0.0, 0x1p-1, -0x1.8p52", writer.buffered());
}
