//! Generates `src/binary/libm_data.zig` from musl's copies of ARM optimized-routines `exp_data.c` and
//! `log_data.c` (MIT, Copyright (c) 2018 Arm Limited): the tables glibc's `exp` and `log` use.
//!
//! `zig build libm-data -- MUSL_MATH_DIR OUTPUT.zig` reads `src/math` of a musl source tree that has
//! both files (Zig 0.15 bundles one under `lib/libc/musl/src/math`; Zig 0.16 bundles only
//! `exp_data.c`) and writes a new file; an existing output is refused.

const std = @import("std");

pub fn main(init: std.process.Init) !void {
    const args = try init.minimal.args.toSlice(init.arena.allocator());
    if (args.len != 3) {
        try std.Io.File.stderr().writeStreamingAll(init.io, "usage: zig build libm-data -- MUSL_MATH_DIR OUTPUT.zig\n");
        std.process.exit(1);
    }
    const allocator = init.arena.allocator();
    const dir = try std.Io.Dir.cwd().openDir(init.io, args[1], .{});
    defer dir.close(init.io);
    const exp = try dir.readFileAlloc(init.io, "exp_data.c", allocator, .limited(1 << 20));
    const log = try dir.readFileAlloc(init.io, "log_data.c", allocator, .limited(1 << 20));
    var output: std.Io.Writer.Allocating = .init(allocator);
    try render(allocator, &output.writer, exp, log);
    const file = try std.Io.Dir.cwd().createFile(init.io, args[2], .{ .exclusive = true });
    defer file.close(init.io);
    try file.writeStreamingAll(init.io, output.written());
}

